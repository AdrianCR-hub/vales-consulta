-- Esquema corregido para PostgreSQL, alineado con los nombres usados por la API.
-- Ejecutar dentro de la base `vales` en una instalación nueva.

CREATE TABLE IF NOT EXISTS logis_zonal (
    id_zona VARCHAR(2) PRIMARY KEY,
    nom_zona VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS logis_localidad (
    id_localidad VARCHAR(2) PRIMARY KEY,
    nom_localidad VARCHAR(100) NOT NULL,
    id_zona VARCHAR(2) NOT NULL REFERENCES logis_zonal(id_zona)
);

CREATE TABLE IF NOT EXISTS logis_centro_costo (
    cod_centro_costo VARCHAR(15) PRIMARY KEY,
    descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS persona (
    codigo_persona INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    ap_paterno VARCHAR(100),
    ap_materno VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS unidad_organizativa (
    cod_uni_organizativa VARCHAR(10) PRIMARY KEY,
    unidad_organizativa VARCHAR(150) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS trabajador (
    dni VARCHAR(8) PRIMARY KEY,
    codigo_persona INTEGER NOT NULL REFERENCES persona(codigo_persona),
    cod_estado BOOLEAN NOT NULL DEFAULT TRUE,
    centro_costo VARCHAR(15) REFERENCES logis_centro_costo(cod_centro_costo),
    cod_uni_organizativa VARCHAR(10) REFERENCES unidad_organizativa(cod_uni_organizativa)
);

CREATE TABLE IF NOT EXISTS proveedor (
    cod_proveedor VARCHAR(11) PRIMARY KEY,
    razon_social VARCHAR(250) NOT NULL
);

CREATE TABLE IF NOT EXISTS logis_contrato_vale (
    cod_contrato VARCHAR(10) PRIMARY KEY,
    ruc VARCHAR(11) NOT NULL REFERENCES proveedor(cod_proveedor),
    monto_total NUMERIC(14,2),
    fecha_inicio DATE,
    fecha_fin DATE,
    observacion TEXT,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS logis_unidad_maquinaria (
    codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(150),
    tipo_vehiculo VARCHAR(100),
    placa VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS estado_vale (
    codigo INTEGER PRIMARY KEY,
    descripcion VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO estado_vale (codigo, descripcion) VALUES
    (0, 'EMITIDO'),
    (1, 'AUTORIZADO'),
    (3, 'USADO'),
    (4, 'ANULADO')
ON CONFLICT (codigo) DO UPDATE SET descripcion = EXCLUDED.descripcion;

CREATE TABLE IF NOT EXISTS logis_vales (
    codigo_vale VARCHAR(10) PRIMARY KEY,
    cod_zonal VARCHAR(2) NOT NULL REFERENCES logis_zonal(id_zona),
    cod_localidad VARCHAR(2) NOT NULL REFERENCES logis_localidad(id_localidad),
    cod_proveedor VARCHAR(11) NOT NULL REFERENCES proveedor(cod_proveedor),
    nrocontrato VARCHAR(10) REFERENCES logis_contrato_vale(cod_contrato),
    cod_trabajador VARCHAR(8) NOT NULL REFERENCES trabajador(dni),
    fecha_emision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_suministro VARCHAR(15),
    cantidad_emitida NUMERIC(14,2),
    precio NUMERIC(14,2),
    cod_centrocosto VARCHAR(15) REFERENCES logis_centro_costo(cod_centro_costo),
    codigo_unidad INTEGER REFERENCES logis_unidad_maquinaria(codigo),
    estado_vale INTEGER NOT NULL DEFAULT 0 REFERENCES estado_vale(codigo),
    observacion TEXT,
    fecha_consumo TIMESTAMP,
    cantidad_consumida NUMERIC(14,2),
    precio_real NUMERIC(14,2),
    importe NUMERIC(14,2),
    ticket VARCHAR(15),
    usuario VARCHAR(8),
    codigo_factura INTEGER,
    observacion_anulacion TEXT,
    fecha_operacion_autorizacion TIMESTAMP,
    fecha_anulacion TIMESTAMP,
    estado_comprobante BOOLEAN NOT NULL DEFAULT FALSE,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_logis_vales_consumo ON logis_vales(fecha_consumo)
    WHERE estado_vale = 3 AND estado = TRUE;
CREATE INDEX IF NOT EXISTS idx_logis_vales_localidad ON logis_vales(cod_localidad);
